    public static int good(int[][] land) {

        int m = land.length;
        int n = land[0].length;

        int[][] goodLand = new int[m][n];
        int side = 0;

        for (int i = 0; i < m; i++) {
            for (int j = 0; j < n; j++) {
                if (land[i][j] == 1) {
                    if (i == 0 || j == 0) goodLand[i][j] = 1;

                    else {
                        goodLand[i][j] = Math.min(Math.min(goodLand[i - 1][j], goodLand[i][j - 1]), goodLand[i - 1][j - 1]) + 1;
                    }
                }
                side = Math.max(side, goodLand[i][j]);
            }
        }

        return side * side;

    }
